"""Write one `status.py` for a work line: after a compaction or a restart the line runs it once instead of re-checking
each thing by hand (lesson L-042). The generated script only reads, uses only the standard library and prints at most
--max-lines lines (default 60), each cut to --width characters:

  LOG      the last --log-lines lines of each log (read from the end of the file, so a large log costs nothing)
  HASH     the last lines of each hash file, and the SHA-256 of each --checksum file
  DISK     free space in GiB on the --disk drive against --disk-min-gib (GiB = 2^30 bytes, lesson L-031)
  GIT      branch, upstream ahead / behind, changed-file count and the last commits of the --git worktree
  OUT      the newest --output-count files under each output folder, with size and age

A missing path prints MISSING; a missing path or a disk below the threshold makes status.py exit 1.

Settings come from --config FILE (JSON, below) and/or the flags; a flag replaces the config's value.

  {"schema_version": 1, "name": "line-a", "logs": ["run/out.log"], "log_lines": 8, "hash_files": ["run/hashes.txt"],
   "checksum": ["build/app.zip"], "outputs": ["run/frames"], "output_count": 5, "disk": "D:/", "disk_min_gib": 20,
   "git": ".", "max_lines": 60, "width": 160}

Relative paths are resolved against the config file's folder (flags: the current folder) and written into status.py
as absolute paths. An existing --out file is not replaced without --force.
"""
import argparse
import json
import pathlib
import sys

KEYS = {"name": str, "logs": list, "log_lines": int, "hash_files": list, "checksum": list, "outputs": list,
        "output_count": int, "disk": str, "disk_min_gib": (int, float), "git": str, "max_lines": int, "width": int}
DEFAULTS = {"name": "status", "logs": [], "log_lines": 8, "hash_files": [], "checksum": [], "outputs": [],
            "output_count": 5, "disk": None, "disk_min_gib": None, "git": None, "max_lines": 60, "width": 160}
PATH_KEYS = ("logs", "hash_files", "checksum", "outputs")

TEMPLATE = r'''"""status.py for {name}: generated by DIRECTOR-WORK tools/status_gen.py; only reads. Regenerate instead of editing."""
import datetime
import hashlib
import json
import os
import shutil
import subprocess
import sys

CONFIG = json.loads({config!r})
problems = 0
out = []


def say(text=""):
    out.append(str(text)[:CONFIG["width"]])


def age(path):
    s = max(0, int(datetime.datetime.now().timestamp() - os.path.getmtime(path)))
    return f"{{s}}s" if s < 120 else f"{{s // 60}}m" if s < 7200 else f"{{s // 3600}}h"


def size(n):
    for unit in ("B", "KiB", "MiB", "GiB"):
        if n < 1024 or unit == "GiB":
            return f"{{n:.0f}} {{unit}}" if unit == "B" else f"{{n:.1f}} {{unit}}"
        n /= 1024


def tail(path, n):
    with open(path, "rb") as fh:
        fh.seek(0, 2)
        end = fh.tell()
        fh.seek(max(0, end - 65536))
        data = fh.read().decode("utf-8", errors="replace")
    return data.splitlines()[-n:] if n else []


def missing(kind, path):
    global problems
    problems += 1
    say(f"{{kind}} MISSING {{path}}")


def main():
    global problems
    say(f"STATUS {{CONFIG['name']}} {{datetime.datetime.now().astimezone().isoformat(timespec='seconds')}}")
    for path in CONFIG["logs"]:
        if not os.path.isfile(path):
            missing("LOG", path)
            continue
        say(f"LOG {{path}} ({{size(os.path.getsize(path))}}, modified {{age(path)}} ago)")
        for line in tail(path, CONFIG["log_lines"]):
            say("  " + line)
    for path in CONFIG["hash_files"]:
        if not os.path.isfile(path):
            missing("HASH", path)
            continue
        say(f"HASH {{path}} (modified {{age(path)}} ago)")
        for line in tail(path, 3):
            say("  " + line)
    for path in CONFIG["checksum"]:
        if not os.path.isfile(path):
            missing("HASH", path)
            continue
        digest = hashlib.sha256()
        with open(path, "rb") as fh:
            for block in iter(lambda: fh.read(1 << 20), b""):
                digest.update(block)
        say(f"HASH sha256 {{digest.hexdigest()[:16]}} {{path}}")
    if CONFIG["disk"]:
        try:
            free = shutil.disk_usage(CONFIG["disk"]).free / 2 ** 30
        except OSError as e:
            missing("DISK", f"{{CONFIG['disk']}} ({{e}})")
        else:
            low = CONFIG["disk_min_gib"] is not None and free < CONFIG["disk_min_gib"]
            problems += low
            limit = f" (min {{CONFIG['disk_min_gib']}} GiB)" if CONFIG["disk_min_gib"] is not None else ""
            say(f"DISK {{CONFIG['disk']}} free {{free:.1f}} GiB{{limit}} {{'LOW' if low else 'OK'}}")
    if CONFIG["git"]:
        def git(*args):
            return subprocess.run(["git", "-C", CONFIG["git"], *args], capture_output=True, text=True,
                                  encoding="utf-8", errors="replace", timeout=20)
        try:
            st = git("status", "--porcelain=v1", "-b")
        except (OSError, subprocess.TimeoutExpired) as e:
            st = None
            missing("GIT", f"{{CONFIG['git']}} ({{e}})")
        if st is not None and st.returncode:
            missing("GIT", f"{{CONFIG['git']}} (not a git worktree)")
        elif st is not None:
            lines = st.stdout.splitlines()
            branch = lines[0][3:] if lines and lines[0].startswith("## ") else "?"
            say(f"GIT {{CONFIG['git']}} {{branch}}; changed files {{len(lines) - 1}}")
            for line in git("log", "-3", "--format=%h %ad %s", "--date=short").stdout.splitlines():
                say("  " + line)
    for folder in CONFIG["outputs"]:
        if not os.path.isdir(folder):
            missing("OUT", folder)
            continue
        files = []
        for root, _, names in os.walk(folder):
            for n in names:
                p = os.path.join(root, n)
                try:
                    files.append((os.path.getmtime(p), p))
                except OSError:
                    pass
        files.sort(reverse=True)
        say(f"OUT {{folder}}: {{len(files)}} files, newest {{min(len(files), CONFIG['output_count'])}}")
        for _, p in files[:CONFIG["output_count"]]:
            say(f"  {{size(os.path.getsize(p))}}  {{age(p)}} ago  {{os.path.relpath(p, folder)}}")
    limit = CONFIG["max_lines"]
    if len(out) > limit:
        cut = len(out) - (limit - 1)
        del out[limit - 1:]
        say(f"TRUNCATED {{cut}} more lines (max_lines {{limit}})")
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except AttributeError:
        pass
    print("\n".join(out))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
'''


def load_config(path):
    data = json.loads(pathlib.Path(path).read_text(encoding="utf-8-sig"))
    if not isinstance(data, dict) or data.get("schema_version") != 1:
        raise ValueError("schema_version must be 1")
    unknown = sorted(set(data) - set(KEYS) - {"schema_version"})
    if unknown:
        raise ValueError(f"unknown key(s): {', '.join(unknown)}")
    return {k: v for k, v in data.items() if k != "schema_version"}


def settings(a):
    """The merged settings with absolute paths, or raises ValueError."""
    base = pathlib.Path.cwd()
    conf = dict(DEFAULTS)
    if a.config:
        conf.update(load_config(a.config))
        base = pathlib.Path(a.config).resolve().parent
    flags = {"name": a.name, "logs": a.log, "log_lines": a.log_lines, "hash_files": a.hash_file, "checksum": a.checksum,
             "outputs": a.outputs, "output_count": a.output_count, "disk": a.disk, "disk_min_gib": a.disk_min_gib,
             "git": a.git, "max_lines": a.max_lines, "width": a.width}
    for key, value in flags.items():
        if value is not None and value != []:
            conf[key] = value
            if key in PATH_KEYS or key == "git":  # a flag's relative path is the current folder's
                conf[key] = [str((pathlib.Path.cwd() / p).resolve()) for p in value] if isinstance(value, list) \
                    else str((pathlib.Path.cwd() / value).resolve())
    for key, kind in KEYS.items():
        value = conf[key]
        if value is None:
            continue
        if not isinstance(value, kind) or isinstance(value, bool):
            raise ValueError(f"{key}: wrong type")
        if kind is list and not all(isinstance(x, str) and x for x in value):
            raise ValueError(f"{key}: a list of paths")
    for key in PATH_KEYS:
        conf[key] = [str((base / p).resolve()) for p in conf[key]]
    if conf["git"]:
        conf["git"] = str((base / conf["git"]).resolve())
    if conf["disk_min_gib"] is not None and not conf["disk"]:
        raise ValueError("disk_min_gib needs disk")
    for key in ("log_lines", "output_count"):
        if conf[key] < 0:
            raise ValueError(f"{key}: 0 or more")
    if conf["max_lines"] < 5 or conf["width"] < 40:
        raise ValueError("max_lines is 5 or more and width 40 or more")
    if not any(conf[k] for k in PATH_KEYS + ("disk", "git")):
        raise ValueError("nothing to report: give at least one log, hash file, checksum, output folder, disk or git")
    return conf


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True, help="the status.py to write")
    ap.add_argument("--force", action="store_true", help="replace an existing --out file")
    ap.add_argument("--config", metavar="FILE")
    ap.add_argument("--name")
    ap.add_argument("--log", action="append", default=[], metavar="FILE")
    ap.add_argument("--log-lines", type=int)
    ap.add_argument("--hash-file", action="append", default=[], metavar="FILE")
    ap.add_argument("--checksum", action="append", default=[], metavar="FILE")
    ap.add_argument("--outputs", action="append", default=[], metavar="DIR")
    ap.add_argument("--output-count", type=int)
    ap.add_argument("--disk", metavar="PATH", help="a path on the drive to measure, e.g. D:/")
    ap.add_argument("--disk-min-gib", type=float)
    ap.add_argument("--git", metavar="DIR")
    ap.add_argument("--max-lines", type=int)
    ap.add_argument("--width", type=int)
    a = ap.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8")
    try:
        conf = settings(a)
    except (OSError, ValueError) as e:
        print(f"FAIL config: {e}")
        return 2
    out = pathlib.Path(a.out)
    if out.exists() and not a.force:
        print(f"FAIL {out} exists; pass --force to replace it")
        return 2
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(TEMPLATE.format(name=conf["name"], config=json.dumps(conf, ensure_ascii=False)))
    print(f"WROTE {out} ({sum(len(conf[k]) for k in PATH_KEYS)} paths, max_lines {conf['max_lines']}); "
          f"run: python {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
