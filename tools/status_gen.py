def director_code():
    """The status.py functions of the Director sections, with poll_hint.py's log-read rules copied in as they are."""
    source = pathlib.Path(__file__).with_name("poll_hint.py").read_text(encoding="utf-8")
    parts = []
    for name in ("READERS", "ALWAYS", "LOG_LIKE", "SEPARATORS"):
        found = re.search(rf"^{name} = .*$", source, re.M)
        if not found:
            raise ValueError(f"poll_hint.py has no {name}")
        parts.append(found.group())
    found = re.search(r"^def read_targets.*?(?=^\S)", source, re.M | re.S)
    if not found:
        raise ValueError("poll_hint.py has no read_targets")
    return "\n".join(parts) + "\n\n\n" + found.group().rstrip() + "\n\n" + DIRECTOR_CODE


def director_settings(conf, base):
    """Check the Director sections and make their paths absolute; raises ValueError."""
    def text(value, where, empty=False):
        if not isinstance(value, str) or (not value and not empty):
            raise ValueError(f"{where}: a string")
        return value

    def regex(value, where):
        try:
            re.compile(text(value, where))
        except re.error as e:
            raise ValueError(f"{where}: not a regex ({e})")
        return value

    def only(value, where, keys):
        unknown = sorted(set(value) - set(keys))
        if unknown:
            raise ValueError(f"{where}: unknown key(s) {', '.join(unknown)}")

    def absolute(value):
        # os.path.abspath, not Path.resolve(): audit.globs hold '*', and Python 3.9 on Windows raises
        # WinError 123 when resolve() meets a wildcard (seen on the GitHub runner, not on a newer 3.9 build).
        return os.path.abspath(os.path.join(str(base), value))

    page = conf["po_page"]
    if page is not None:
        only(page, "po_page", ("path", "counts", "extract"))
        page["path"] = absolute(text(page.get("path"), "po_page.path"))
        if page.get("extract") is not None:
            regex(page["extract"], "po_page.extract")
        counts = page.get("counts")
        if not isinstance(counts, list) or not counts or not all(isinstance(c, dict) for c in counts):
            raise ValueError("po_page.counts: a list of {label, regex} or {label, list, field, value}")
        for c in counts:
            only(c, "po_page.counts", ("label", "regex", "list", "field", "value"))
            text(c.get("label"), "po_page.counts.label")
            if (c.get("regex") is None) == (c.get("list") is None):
                raise ValueError(f"po_page.counts {c.get('label')}: give regex or list, one of them")
            if c.get("regex") is not None:
                regex(c["regex"], "po_page.counts.regex")
            else:
                text(c["list"], "po_page.counts.list")
                for key in ("field", "value"):
                    if c.get(key) is not None:
                        text(c[key], f"po_page.counts.{key}", empty=True)
    orders = conf["orders"]
    if orders is not None:
        only(orders, "orders", ("dir", "glob", "closed", "show"))
        orders["dir"] = absolute(text(orders.get("dir"), "orders.dir"))
        orders["glob"] = text(orders.get("glob", "WO-*.md"), "orders.glob")
        orders["closed"] = regex(orders.get("closed", CLOSED), "orders.closed")
        orders.setdefault("show", 8)
        if not isinstance(orders["show"], int) or isinstance(orders["show"], bool) or orders["show"] < 0:
            raise ValueError("orders.show: 0 or more")
    sends = conf["pending_sends"]
    if sends is not None:
        only(sends, "pending_sends", ("path", "unsent"))
        sends["path"] = absolute(text(sends.get("path"), "pending_sends.path"))
        sends["unsent"] = regex(sends.get("unsent", UNSENT), "pending_sends.unsent")
    audit = conf["audit"]
    if audit is not None:
        only(audit, "audit", ("globs", "hours"))
        globs = audit.get("globs")
        if isinstance(globs, str):
            globs = [globs]
        if not isinstance(globs, list) or not globs or not all(isinstance(g, str) and g for g in globs):
            raise ValueError("audit.globs: a list of globs")
        audit["globs"] = [absolute(g) for g in globs]
        audit.setdefault("hours", 1)
        if not isinstance(audit["hours"], (int, float)) or isinstance(audit["hours"], bool) or audit["hours"] <= 0:
            raise ValueError("audit.hours: more than 0")
    for proc in conf["processes"]:
        if not isinstance(proc, dict):
            raise ValueError("processes: a list of {label, match}")
        only(proc, "processes", ("label", "match"))
        text(proc.get("label"), "processes.label")
        regex(proc.get("match"), "processes.match")


def load_config(path):
    data = json.loads(pathlib.Path(path).read_text(encoding="utf-8-sig"))
    if not isinstance(data, dict) or data.get("schema_version") != 1:
        raise ValueError("schema_version must be 1")
    unknown = sorted(set(data) - set(KEYS) - {"schema_version"})
    if unknown:
        raise ValueError(f"unknown key(s): {', '.join(unknown)}")
    return {k: v for k, v in data.items() if k != "schema_version"}


def settings(a):
    """The merged settings with absolute paths, or raises ValueError."""
    base = pathlib.Path.cwd()
    conf = dict(DEFAULTS)
    if a.config:
        conf.update(load_config(a.config))
        base = pathlib.Path(a.config).resolve().parent
    flags = {"name": a.name, "logs": a.log, "log_lines": a.log_lines, "hash_files": a.hash_file, "checksum": a.checksum,
             "outputs": a.outputs, "output_count": a.output_count, "disk": a.disk, "disk_min_gib": a.disk_min_gib,
             "git": a.git, "max_lines": a.max_lines, "width": a.width}
    for key, value in flags.items():
        if value is not None and value != []:
            conf[key] = value
            if key in PATH_KEYS or key == "git":  # a flag's relative path is the current folder's
                conf[key] = [str((pathlib.Path.cwd() / p).resolve()) for p in value] if isinstance(value, list) \
                    else str((pathlib.Path.cwd() / value).resolve())
    for key, kind in KEYS.items():
        value = conf[key]
        if value is None:
            continue
        if not isinstance(value, kind) or isinstance(value, bool):
            raise ValueError(f"{key}: wrong type")
        if kind is list and key != "processes" and not all(isinstance(x, str) and x for x in value):
            raise ValueError(f"{key}: a list of paths")
    for key in PATH_KEYS:
        conf[key] = [str((base / p).resolve()) for p in conf[key]]
    if conf["git"]:
        conf["git"] = str((base / conf["git"]).resolve())
    director_settings(conf, base)
    if conf["disk_min_gib"] is not None and not conf["disk"]:
        raise ValueError("disk_min_gib needs disk")
    for key in ("log_lines", "output_count"):
        if conf[key] < 0:
            raise ValueError(f"{key}: 0 or more")
    if conf["max_lines"] < 5 or conf["width"] < 40:
        raise ValueError("max_lines is 5 or more and width 40 or more")
    if not any(conf[k] for k in PATH_KEYS + ("disk", "git") + DIRECTOR_KEYS):
        raise ValueError("nothing to report: give at least one log, hash file, checksum, output folder, disk, git or "
                         "Director section")
    return conf


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True, help="the status.py to write")
    ap.add_argument("--force", action="store_true", help="replace an existing --out file")
    ap.add_argument("--config", metavar="FILE")
    ap.add_argument("--name")
    ap.add_argument("--log", action="append", default=[], metavar="FILE")
    ap.add_argument("--log-lines", type=int)
    ap.add_argument("--hash-file", action="append", default=[], metavar="FILE")
    ap.add_argument("--checksum", action="append", default=[], metavar="FILE")
    ap.add_argument("--outputs", action="append", default=[], metavar="DIR")
    ap.add_argument("--output-count", type=int)
    ap.add_argument("--disk", metavar="PATH", help="a path on the drive to measure, e.g. D:/")
    ap.add_argument("--disk-min-gib", type=float)
    ap.add_argument("--git", metavar="DIR")
    ap.add_argument("--max-lines", type=int)
    ap.add_argument("--width", type=int)
    a = ap.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8")
    try:
        conf = settings(a)
    except (OSError, ValueError) as e:
        print(f"FAIL config: {e}")
        return 2
    try:
        code = director_code()
    except (OSError, ValueError) as e:
        print(f"FAIL tools: {e}")
        return 2
    out = pathlib.Path(a.out)
    if out.exists() and not a.force:
        print(f"FAIL {out} exists; pass --force to replace it")
        return 2
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(TEMPLATE.format(name=conf["name"], config=json.dumps(conf, ensure_ascii=False),
                                 director_code=code))
    sections = sum(1 for k in DIRECTOR_KEYS if conf[k])
    print(f"WROTE {out} ({sum(len(conf[k]) for k in PATH_KEYS)} paths, {sections} Director sections, "
          f"max_lines {conf['max_lines']}); "
          f"run: python {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
